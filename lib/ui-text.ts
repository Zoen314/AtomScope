/** Presentation-only translations for legacy parser/link diagnostics and saved metadata. */
export function englishMessage(value: string): string {
  const replacements: [RegExp, string][] = [
    [/分享链接损坏或版本不受支持：/g, 'Invalid or unsupported structure link: '],
    [/仅支持 SharePayloadV1/g, 'Only SharePayloadV1 is supported'],
    [/format 无效/g, 'Invalid format'], [/结构晶胞字段无效/g, 'Invalid cell fields'],
    [/元素与坐标数量不一致/g, 'Element and coordinate counts do not match'],
    [/结构包含 NaN 或无穷数/g, 'Structure contains non-finite values'],
    [/压缩链接为 (.*?) 字符，超过 100,000 字符的 URL-only 上限/g, 'Link has $1 characters; maximum is 100,000'],
    [/原子编号须为 (.*?) 的整数/g, 'Atom IDs must be integers in $1'],
    [/请选择不同的原子/g, 'Select distinct atoms'],
    [/请选择 (.*?) 个不同且有效的原子/g, 'Select $1 distinct valid atoms'],
    [/原子在周期最小镜像下重合，夹角未定义/g, 'Angle is undefined: atoms coincide under periodic minimum images'],
    [/LAMMPS data 不记录 units；按 Å 解释/g, 'Units: angstrom (not stored in LAMMPS data)'],
    [/LAMMPS data 不记录 boundary；按 ppp 解释/g, 'Boundary: ppp (not stored in LAMMPS data)'],
    [/类型 (.*?) 缺少元素映射；已关闭自动键。可提供 --type-map 1:P,2:O,3:H/g, 'Types $1 have no element mapping. Bonds disabled; supply --type-map 1:P,2:O,3:H'],
    [/推断键超过浏览器安全上限 (.*?)，已默认隐藏；请降低灵敏度或设置元素对阈值。/g, 'Bond count exceeds the browser limit ($1). Reduce the multiplier or use pair overrides.'],
    [/无法读取数值“(.*?)”/g, 'Invalid numeric value: $1'],
    [/晶胞体积为零或矩阵奇异|晶胞矩阵奇异，无法计算周期最小镜像/g, 'Cell is singular or has zero volume'],
    [/无法判断文件是 POSCAR 还是 LAMMPS data/g, 'Unrecognized format. Use POSCAR or LAMMPS data.'],
    [/POSCAR 至少需要 8 行/g, 'POSCAR needs at least 8 lines'],
    [/v1 只支持单个正比例因子，不支持三分量 scale/g, 'Use a single positive scale; three-component scale is unsupported'],
    [/v1 不支持负比例因子（目标体积），请先转换为正比例因子/g, 'Negative volume scale is unsupported; convert to a positive scale'],
    [/晶胞向量必须包含 3 个数/g, 'Cell vectors need 3 numbers'],
    [/v1 需要 VASP5\/6 元素行；VASP4 请提供元素映射或先转换文件/g, 'VASP5/6 element symbols are required; convert VASP4 first'],
    [/未知元素符号“(.*?)”/g, 'Unknown element: $1'],
    [/元素数量列必须与元素行一一对应，且均为非负整数/g, 'Element counts must be nonnegative integers matching the element row'],
    [/坐标模式必须是 Direct 或 Cartesian/g, 'Coordinate mode must be Direct or Cartesian'],
    [/声明 (.*?) 个原子，但坐标行不足/g, '$1 atoms declared, but coordinate rows are missing'],
    [/坐标行少于 3 列/g, 'Coordinate row needs at least 3 columns'],
    [/v1 只支持 restricted triclinic（xy xz yz），不支持 general triclinic/g, 'Only restricted triclinic (xy xz yz) is supported'],
    [/未找到 Atoms # atomic 段/g, 'Missing Atoms # atomic section'],
    [/v1 仅支持带明确注释的 Atoms # atomic；full\/charge\/molecular 暂不支持/g, 'Use explicit Atoms # atomic; full/charge/molecular styles are unsupported'],
    [/文件头缺少“<N> atoms”/g, 'Header is missing <N> atoms'],
    [/缺少 x\/y\/z 盒子边界/g, 'Missing x/y/z box bounds'],
    [/类型 (.*?) 的元素“(.*?)”无效/g, 'Invalid element $2 for type $1'],
    [/文件头声明 (.*?) 个原子，但 Atoms 段读取到 (.*?) 行/g, 'Header declares $1 atoms; Atoms section has $2 rows'],
    [/atomic 行必须是 id type x y z，或额外包含 ix iy iz/g, 'Atomic rows must be id type x y z, optionally followed by ix iy iz'],
    [/id 和 type 必须是整数/g, 'id and type must be integers'], [/ix iy iz 必须是整数/g, 'ix iy iz must be integers'],
  ];
  return replacements.reduce((text, [pattern, replacement]) => text.replace(pattern, replacement), value);
}
